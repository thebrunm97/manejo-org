-- 6. RLS Policies

-- organizacoes: Membros podem ver sua organização
CREATE POLICY "Membros podem ver sua organizacao" 
ON public.organizacoes FOR SELECT 
TO authenticated 
USING (
    EXISTS (
        SELECT 1 FROM public.organizacao_membros 
        WHERE organizacao_id = public.organizacoes.id 
        AND propriedade_id IN (SELECT id FROM public.propriedades WHERE user_id = auth.uid())
    ) OR 
    EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin')
);

-- organizacao_membros: Membros podem ver outros membros da mesma org
CREATE POLICY "Membros podem ver membros da mesma organizacao" 
ON public.organizacao_membros FOR SELECT 
TO authenticated 
USING (
    organizacao_id IN (
        SELECT organizacao_id FROM public.organizacao_membros 
        WHERE propriedade_id IN (SELECT id FROM public.propriedades WHERE user_id = auth.uid())
    ) OR 
    EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin')
);

-- Admin policies
CREATE POLICY "Admins podem tudo nas organizacoes" 
ON public.organizacoes FOR ALL 
TO authenticated 
USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'));

CREATE POLICY "Admins podem tudo nos membros" 
