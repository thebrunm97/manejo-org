-- 1. Create organizacoes table
CREATE TABLE IF NOT EXISTS public.organizacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    cnpj TEXT UNIQUE,
    tipo TEXT CHECK (tipo IN ('cooperativa', 'associacao', 'spg', 'grupo_informal')),
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Create organizacao_membros (N:N with Propriedade)
CREATE TABLE IF NOT EXISTS public.organizacao_membros (
    organizacao_id BIGINT REFERENCES public.organizacoes(id) ON DELETE CASCADE,
    propriedade_id BIGINT REFERENCES public.propriedades(id) ON DELETE CASCADE,
    role TEXT DEFAULT 'membro',
    data_filiacao DATE DEFAULT CURRENT_DATE,
    PRIMARY KEY (organizacao_id, propriedade_id)
);

-- 3. Data Migration for demandas_coletivas
-- Create a default organization to bridge existing data
DO $$
DECLARE
    default_org_id BIGINT;
BEGIN
    -- Check if we already have a default org
    SELECT id INTO default_org_id FROM public.organizacoes WHERE nome = 'Cooperativa Central (Padrão)' LIMIT 1;
    
    IF default_org_id IS NULL THEN
        INSERT INTO public.organizacoes (nome, tipo) 
        VALUES ('Cooperativa Central (Padrão)', 'cooperativa')
        RETURNING id INTO default_org_id;
    END IF;

    -- Update existing demands to point to this default org if they are null
    UPDATE public.demandas_coletivas 
    SET cooperativa_id = default_org_id 
    WHERE cooperativa_id IS NULL;
END $$;

